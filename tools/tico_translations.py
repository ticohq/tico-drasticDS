def slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "_", text.lower()).strip("_")


def label_key(text: str) -> str:
    return "settings_drastic_" + slug(text)


def tab_key(text: str) -> str:
    return "settings_drastic_tab_" + slug(text)


def value_key(text: str) -> str:
    return "settings_drastic_value_" + slug(text)


def main() -> int:
    settings = json.loads(SETTINGS.read_text(encoding="utf-8"))
    entries: dict[str, tuple[str, ...]] = {}

    def add(key: str, english: str, translated: tuple[str, ...]) -> str:
        if len(translated) != len(LANGUAGES) - 1:
            raise SystemExit(f"{english}: expected {len(LANGUAGES) - 1} translations")
        entries[key] = (english, *translated)
        return key

    def english_of(label: str) -> str:
        # settings.json may already hold a key from an earlier run
        for english in TEXT:
            if label in (english, label_key(english), tab_key(english)):
                return english
        raise SystemExit(f"no translation for label {label!r}")

    for tab in settings["tabs"]:
        english = english_of(tab["name"])
        tab["name"] = add(tab_key(english), english, TEXT[english])
        for section in tab["sections"]:
            section["title"] = tab["name"]
            for option in section["options"]:
                english = english_of(option["label"])
                option["label"] = add(label_key(english), english, TEXT[english])
                for choice in option.get("choices", []):
                    if choice["label"] in CHOICES:
                        add(value_key(choice["label"]), choice["label"],
                            CHOICES[choice["label"]])
    # options the overlay adds in game
    add(label_key("Custom shader"), "Custom shader", TEXT["Custom shader"])
    add(value_key("None found"), "None found", CHOICES["None found"])
    for key, texts in MESSAGES.items():
        entries[key] = texts

    SETTINGS.write_text(json.dumps(settings, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    for index, language in enumerate(LANGUAGES):
        path = LANG_DIR / f"{language}.json"
        strings = json.loads(path.read_text(encoding="utf-8"))
        strings = {key: value for key, value in strings.items()
                   if not key.startswith(("settings_drastic_", "drastic_"))}
        for key, texts in entries.items():
            strings[key] = texts[index]
        path.write_text(json.dumps(strings, indent=2, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    print(f"{len(entries)} keys written to {len(LANGUAGES)} languages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
